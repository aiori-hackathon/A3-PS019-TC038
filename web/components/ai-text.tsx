"use client";

import { Fragment, type ReactNode } from "react";

/** Minimal, safe rendering of LLM output: paragraphs, "- " bullets, **bold**, `code`, and clickable PT-IDs. No HTML is injected. */
export function AiText({ text, onFinding }: { text: string; onFinding?: (pt: string) => void }) {
  const inline = (s: string, k: string): ReactNode[] =>
    s.split(/(\*\*[^*]+\*\*|`[^`]+`|PT-\d{5})/g).filter(Boolean).map((part, i) => {
      const key = `${k}-${i}`;
      if (part.startsWith("**") && part.endsWith("**")) return <b key={key}>{inline(part.slice(2, -2), key)}</b>;
      if (part.startsWith("`") && part.endsWith("`")) return <code key={key}>{part.slice(1, -1)}</code>;
      if (/^PT-\d{5}$/.test(part) && onFinding)
        return <button key={key} className="btn sm ghost mono" style={{ minHeight: 22, padding: "0 4px", fontSize: 12 }} onClick={() => onFinding(part)}>{part}</button>;
      return <Fragment key={key}>{part}</Fragment>;
    });
  const blocks: ReactNode[] = [];
  let bullets: string[] = [];
  const flush = (k: number) => {
    if (bullets.length) blocks.push(<ul key={`u${k}`} style={{ margin: "4px 0", paddingLeft: 18, display: "grid", gap: 4 }}>{bullets.map((b, i) => <li key={i}>{inline(b, `b${k}${i}`)}</li>)}</ul>);
    bullets = [];
  };
  text.split("\n").forEach((line, i) => {
    const t = line.trim();
    const m = /^([-*•]|\d+\.)\s+(.*)$/.exec(t);
    if (m) {
      bullets.push(m[2]);
      return;
    }
    flush(i);
    if (t) blocks.push(<p key={`p${i}`} style={{ margin: "4px 0" }}>{inline(t.replace(/^#+\s*/, ""), `p${i}`)}</p>);
  });
  flush(-1);
  return <div style={{ lineHeight: 1.6 }}>{blocks}</div>;
}

export const MAX_CHARS = 300;

/** Live character counter for chat inputs; red near and over the limit. */
export function CharCount({ n }: { n: number }) {
  const color = n > MAX_CHARS ? "var(--bad)" : n > MAX_CHARS * 0.85 ? "var(--sev-medium)" : "var(--text-3)";
  return <span className="num small" style={{ color, minWidth: 54, textAlign: "right" }} aria-live="polite" title="Questions are limited to 300 characters">{n}/{MAX_CHARS}</span>;
}

export function ModelBadge({ mode, model }: { mode?: string; model?: string }) {
  if (mode === "guard") return <span className="tag" style={{ color: "var(--sev-medium)" }} title="The safety guard stopped this prompt before it reached the LLM">Blocked by safety guard</span>;
  if (mode === "error") return <span className="tag" style={{ color: "var(--bad)" }}>Not sent</span>;
  if (mode !== "llm") return <span className="tag" title="Offline answer engine (no LLM configured or reachable)">offline engine</span>;
  return <span className="tag" title="Generated by an LLM on Groq from metadata only">Groq · {model?.split("/").pop()}</span>;
}
